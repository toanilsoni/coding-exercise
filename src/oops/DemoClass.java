package oops;

public class DemoClass {

	String firstName;
	String lastName;

	public DemoClass() {

	}
	
	public DemoClass(String firstName, String lastName) {
		this.firstName = firstName;
		this.lastName = lastName;
	}

	public String getFirstName() {
		return firstName;
	}

	public void setFirstName(String lastName) {
		this.lastName = lastName;
	}

	

}